// WebP test fixtures (binary byte arrays) for the EXT_texture_webp decode path.
//
// rasterminal vendors libwebp's decode-only subset (no encoder), so these were generated
// offline once with Pillow (which wraps libwebp). Reproduction:
//
//   python3 - <<'PY'
//   from PIL import Image
//   # 4x4 solid (200,90,40) opaque  ->  VP8 lossy
//   Image.new('RGB', (4, 4), (200, 90, 40)).save('lossy.webp', lossless=False, quality=90)
//   # 4x4 quadrants TL=red TR=green BL=blue BR=white  ->  VP8L lossless
//   q = Image.new('RGBA', (4, 4))
//   for y in range(4):
//       for x in range(4):
//           q.putpixel((x, y), ((255,0,0,255) if x<2 and y<2 else (0,255,0,255) if x>=2 and y<2
//                               else (0,0,255,255) if x<2 else (255,255,255,255)))
//   q.save('quad.webp', lossless=True, exact=True)
//   # 4x4 transparent field + one semi-transparent (255,0,0,128) texel  ->  VP8L lossless + alpha
//   a = Image.new('RGBA', (4, 4), (0, 0, 0, 0)); a.putpixel((1, 1), (255, 0, 0, 128))
//   a.save('alpha.webp', lossless=True, exact=True)
//   # 1x1 solid (123,45,67)  ->  VP8L lossless (minimum dimensions)
//   Image.new('RGBA', (1, 1), (123, 45, 67, 255)).save('one.webp', lossless=True, exact=True)
//   # 6x2 non-square: row0 px x = (x*40,0,0), row1 px x = (0,x*40,0)  ->  VP8L lossless
//   r = Image.new('RGBA', (6, 2))
//   for x in range(6):
//       r.putpixel((x, 0), (x*40, 0, 0, 255)); r.putpixel((x, 1), (0, x*40, 0, 255))
//   r.save('rect.webp', lossless=True, exact=True)
//   # 4x4 RGB (200,100,50) with alpha = (x+y)*30  ->  VP8 lossy + ALPH chunk (lossy colour, exact alpha)
//   la = Image.new('RGBA', (4, 4))
//   for y in range(4):
//       for x in range(4): la.putpixel((x, y), (200, 100, 50, (x+y)*30))
//   la.save('lossy_alpha.webp', lossless=False, quality=90)
//   # 4x4 animated, frame0 red + frame1 green  ->  VP8X + ANIM (must be rejected; still images only)
//   f0 = Image.new('RGBA', (4, 4), (255,0,0,255)); f1 = Image.new('RGBA', (4, 4), (0,255,0,255))
//   f0.save('anim.webp', save_all=True, append_images=[f1], duration=100, loop=0, lossless=True)
//   PY
//
// k_webp_corrupt_body is quad.webp with four bytes near the end of the compressed stream XORed
// by 0xFF (the RIFF + VP8L header stays intact) — WebPGetFeatures succeeds but the decode fails.
//
// Reference RGBA decode of each (used by the test expectations):
//   lossy solid  -> ~(201, 90, 41, 255) everywhere (VP8 is lossy; loose tolerance)
//   quad         -> TL=(255,0,0) TR=(0,255,0) BL=(0,0,255) BR=(255,255,255), all opaque (exact)
//   alpha        -> (0,0,0,0) everywhere except pixel (1,1) = (255,0,0,128) (exact)
//   one          -> (123,45,67,255) (exact)
//   rect         -> (0,0)=(0,0,0) (5,0)=(200,0,0) (5,1)=(0,200,0), all opaque (exact)
//   lossy_alpha  -> RGB ~(201,100,50) (loose); alpha exact: (0,0)=0 (3,0)=90 (3,3)=180
//   animated, corrupt_body -> decode rejected (returns false)

