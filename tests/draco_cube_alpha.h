// decoded alpha correspondence (the two anchors the test asserts are marked):
//   (-1,-1,-1) -> 0.251   <- test anchor (red,   a 64/255)
//   (-1, 1, 1) -> 0.125
//   ( 1, 1, 1) -> 0.753   <- test anchor (blue,  a 192/255)
//   (-1,-1, 1) -> 0.878
//   ( 1,-1, 1) -> 1.000
